-- Ez a script létrehozza az új `public.products` táblát a megadott Excel/táblázat 
-- kép alapján, beállítja az RLS (Row Level Security) és Storage szabályokat,
-- valamint feltölti a mintarekordokat.
-- Futtasd a Supabase Dashboard -> SQL Editor felületén!
