-- 1. Új termékek tábla létrehozása
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cikkszam TEXT,
    megnevezes TEXT NOT NULL,
    kategoria TEXT,
    keszlet NUMERIC DEFAULT 0,
    utanrendelheto BOOLEAN DEFAULT TRUE,
    suly_g NUMERIC,
    kiszereles NUMERIC DEFAULT 1,
    bonthato BOOLEAN DEFAULT FALSE,
    mennyisegi_egyseg TEXT DEFAULT 'db',
    netto_ar NUMERIC DEFAULT 0,
    afa_kulcs NUMERIC DEFAULT 27,
    garancia TEXT,
    leiras TEXT,
    termekkep_link TEXT,
    aktiv BOOLEAN DEFAULT TRUE,
    fenyes_ar NUMERIC,
    standard_matt_ar NUMERIC,
    ultra_matt_ar NUMERIC,
    alucink_ar NUMERIC,
    slug TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Indexek a gyorsabb kereséshez és szűréshez
CREATE INDEX IF NOT EXISTS idx_products_kategoria ON public.products(kategoria);
CREATE INDEX IF NOT EXISTS idx_products_aktiv ON public.products(aktiv);
CREATE INDEX IF NOT EXISTS idx_products_cikkszam ON public.products(cikkszam);
CREATE INDEX IF NOT EXISTS idx_products_slug ON public.products(slug);

-- 2. RLS (Row Level Security) bekapcsolása
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Olvasási jog mindenki számára (anon és bejelentkezett felhasználók)
DROP POLICY IF EXISTS "Termékek olvasása mindenki számára" ON public.products;
CREATE POLICY "Termékek olvasása mindenki számára" 
ON public.products FOR SELECT 
TO anon, authenticated 
USING (true);

-- Adminisztráció (beszúrás, módosítás, törlés) engedélyezése az admin felülethez
DROP POLICY IF EXISTS "Termékek adminisztrációja" ON public.products;
CREATE POLICY "Termékek adminisztrációja" 
ON public.products FOR ALL 
TO anon, authenticated 
USING (true) 
WITH CHECK (true);

-- 3. Storage bucket beállítása termékképekhez
INSERT INTO storage.buckets (id, name, public) 
VALUES ('termekek', 'termekek', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS szabályok (képfeltöltés és megtekintés)
DROP POLICY IF EXISTS "Termék képek publikus megtekintése" ON storage.objects;
CREATE POLICY "Termék képek publikus megtekintése" 
ON storage.objects FOR SELECT 
TO anon, authenticated 
USING (bucket_id = 'termekek');

DROP POLICY IF EXISTS "Termék képek feltöltése és kezelése" ON storage.objects;
CREATE POLICY "Termék képek feltöltése és kezelése" 
ON storage.objects FOR ALL 
TO anon, authenticated 
USING (bucket_id = 'termekek') 
WITH CHECK (bucket_id = 'termekek');

